"""Recommend a load mode (incremental, full, incremental+periodic) for each table in the inventory.

Reads inventory/tables.csv, profiles each table's cursor column in Oracle, and writes a
recommendation CSV plus an updated inventory with load_mode and deletes filled in.
Read-only on the Oracle side.

Two ways to run it:

  A. No Python access to Oracle (SQL Developer, DBeaver, SQL*Plus):
       python scripts/check_load_mode.py emit inventory/tables.csv --owner APP_OWNER > load_mode_check.sql
       -- run load_mode_check.sql in your SQL tool, export the result grid as CSV --
       python scripts/check_load_mode.py recommend inventory/tables.csv load_mode_results.csv

  B. Direct (pip install oracledb; thin mode, no Oracle client needed):
       ORACLE_USER=... ORACLE_DSN=host:1521/SERVICE python scripts/check_load_mode.py run \
           inventory/tables.csv --owner APP_OWNER
     The password is prompted for (or read from ORACLE_PASSWORD). Never pass it as an argument.

Both write inventory/load_mode_recommendations.csv and inventory/tables_with_load_mode.csv.
Review every 'review' row with the app team, then copy the decisions into tables.csv.

What it checks per table:
  - NULL cursor values (never ingested by the connector)
  - Whether the cursor moved since Oracle last recorded DML on the table (ALL_TAB_MODIFICATIONS).
    Updates with no cursor movement suggest the app doesn't touch the cursor on update.
  - Truncates since the last stats gather (truncate-and-reload tables need a full load)
  - Deletes since the last stats gather (candidates for hard-delete sync)
  - Primary key present (needed for SCD Type 1 merges and hard-delete sync)

For fresher DML counts, ask the DBA to run EXEC DBMS_STATS.FLUSH_DATABASE_MONITORING_INFO first.
The counts cover the window since stats were last gathered on each table (mods_since).
L and XL tables are sampled (SAMPLE 1 percent) to avoid full scans, so their NULL share is approximate.
"""
import argparse
import csv
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from generate_pipelines import auto_tier  # noqa: E402

SAMPLE_TIERS = ("L", "XL")
SAMPLE_PCT = 1
RESULT_COLS = ["table_name", "num_rows_stats", "checked_rows", "null_cursor_rows", "max_cursor",
               "cursor_moved_since_mods", "inserts", "updates", "deletes", "truncated", "mods_since"]


def read_inventory(path):
    rows = list(csv.DictReader(open(path)))
    for r in rows:
        r["source_table"] = r["source_table"].strip().upper()
        r["cursor_column"] = (r.get("cursor_column") or "").strip().upper()
        r["primary_keys"] = (r.get("primary_keys") or "").strip().upper()
        r["size_gb"] = r.get("size_gb") or "0"
        r["tier"] = (r.get("tier") or "").strip().upper() or auto_tier(float(r["size_gb"]))
        r["cursor_type"] = (r.get("cursor_type") or "DATE").strip().upper()
    return rows


def table_sql(owner, r, cursor_type=None):
    """One SELECT returning one row of RESULT_COLS for a table."""
    t, c = r["source_table"], r["cursor_column"]
    sample = f" SAMPLE ({SAMPLE_PCT})" if r["tier"] in SAMPLE_TIERS else ""
    is_date = (cursor_type or r["cursor_type"]).startswith(("DATE", "TIMESTAMP"))
    if c:
        prof = (f"SELECT COUNT(*) AS checked_rows, COUNT(*) - COUNT({c}) AS null_cursor_rows, "
                f"TO_CHAR(MAX({c})) AS max_cursor, MAX({c}) AS max_cursor_raw FROM {owner}.{t}{sample}")
    else:
        prof = (f"SELECT COUNT(*) AS checked_rows, NULL AS null_cursor_rows, NULL AS max_cursor, "
                f"NULL AS max_cursor_raw FROM {owner}.{t}{sample}")
    moved = ("CASE WHEN m.timestamp IS NULL THEN NULL WHEN s.max_cursor_raw >= m.timestamp "
             "THEN 'Y' ELSE 'N' END") if (c and is_date) else "NULL"
    return (
        f"SELECT '{t}' AS table_name,\n"
        f"       (SELECT num_rows FROM all_tables WHERE owner = '{owner}' AND table_name = '{t}') AS num_rows_stats,\n"
        f"       s.checked_rows, s.null_cursor_rows, s.max_cursor,\n"
        f"       {moved} AS cursor_moved_since_mods,\n"
        f"       m.inserts, m.updates, m.deletes, m.truncated, TO_CHAR(m.timestamp, 'YYYY-MM-DD') AS mods_since\n"
        f"FROM ({prof}) s\n"
        f"LEFT JOIN all_tab_modifications m\n"
        f"  ON m.table_owner = '{owner}' AND m.table_name = '{t}' AND m.partition_name IS NULL"
    )


def emit(rows, owner):
    print("-- Load-mode check for Lakeflow Connect QBC. Read-only. Generated by scripts/check_load_mode.py")
    print("-- Optional, for fresher DML counts (DBA): EXEC DBMS_STATS.FLUSH_DATABASE_MONITORING_INFO;")
    print("-- Run as one statement and export the result grid as CSV (header row included).")
    print("\nUNION ALL\n".join(table_sql(owner, r) for r in rows) + "\n;")


def run(rows, owner):
    try:
        import oracledb
    except ImportError:
        sys.exit("pip install oracledb (or use the emit / recommend path)")
    import getpass
    pw = os.environ.get("ORACLE_PASSWORD") or getpass.getpass("Oracle password: ")
    conn = oracledb.connect(user=os.environ["ORACLE_USER"], password=pw, dsn=os.environ["ORACLE_DSN"])
    cur = conn.cursor()
    results = []
    for r in rows:
        ctype = None
        if r["cursor_column"]:
            cur.execute("SELECT data_type FROM all_tab_columns WHERE owner = :o AND table_name = :t AND column_name = :c",
                        o=owner, t=r["source_table"], c=r["cursor_column"])
            hit = cur.fetchone()
            if not hit:
                results.append({"table_name": r["source_table"], "error": f"cursor {r['cursor_column']} not found"})
                continue
            ctype = hit[0]
        try:
            cur.execute(table_sql(owner, r, ctype))
            results.append(dict(zip(RESULT_COLS, cur.fetchone())))
        except oracledb.DatabaseError as e:
            results.append({"table_name": r["source_table"], "error": str(e).splitlines()[0]})
        print(f"checked {r['source_table']}", file=sys.stderr)
    conn.close()
    return results


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return 0.0


def recommend_one(inv, res):
    """Return (load_mode, deletes, reasons). load_mode 'review' means a person decides."""
    tier, reasons = inv["tier"], []
    if res.get("error"):
        return "review", inv.get("deletes") or "none", [f"check failed: {res['error']}"]
    has_pk, has_cursor = bool(inv["primary_keys"]), bool(inv["cursor_column"])
    small = tier in ("S", "M")
    mode = "incremental"

    if (res.get("truncated") or "").upper() == "YES":
        mode = "full"
        reasons.append("table was truncated since last stats: looks like truncate-and-reload, use a full load")
    elif not has_cursor:
        mode = "full" if small else "review"
        reasons.append("no cursor column: full load every run" + ("" if small else "; on a large table, find a cursor with the app team"))
    else:
        checked, nulls = num(res.get("checked_rows")), num(res.get("null_cursor_rows"))
        if nulls:
            pct = 100 * nulls / checked if checked else 0
            mode = "full" if tier == "S" else "review"
            reasons.append(f"{pct:.1f}% of rows have a NULL cursor and would never load")
        if res.get("cursor_moved_since_mods") == "N" and num(res.get("updates")) > 0:
            if mode == "incremental":
                mode = "incremental+periodic"
            reasons.append(f"{int(num(res['updates']))} updates since {res.get('mods_since')} but the cursor didn't move: "
                           "updates may not touch it; confirm with the app team")
        if num(res.get("checked_rows")) == 0 and num(res.get("num_rows_stats")) == 0:
            reasons.append("table is empty")

    if not has_pk:
        mode = "review"
        reasons.append("no primary key: SCD Type 1 needs one. It doesn't have to be an Oracle constraint; "
                       "ask the app team for a unique column set (APPEND_ONLY only if rows are never updated)")

    deletes = inv.get("deletes") or "none"
    if num(res.get("deletes")) > 0 and has_pk and deletes != "hard":
        deletes = "hard"
        reasons.append(f"{int(num(res['deletes']))} deletes since {res.get('mods_since')}: turn on hard-delete sync")
    if mode == "full" and tier in ("L", "XL"):
        reasons.append(f"full reload of a {tier} table every run is expensive; fixing the cursor is usually better")
    if not reasons:
        reasons.append("cursor looks healthy")
    return mode, deletes, reasons


def recommend(inv_rows, results, outdir):
    # SQL tools export headers in uppercase; normalize so either works
    results = [{k.strip().lower(): v for k, v in r.items()} for r in results]
    by_name = {(r.get("table_name") or "").strip().upper(): r for r in results}
    recs, updated = [], []
    for inv in inv_rows:
        res = by_name.get(inv["source_table"])
        if res is None:
            mode, deletes, reasons = "review", inv.get("deletes") or "none", ["no check result for this table"]
        else:
            mode, deletes, reasons = recommend_one(inv, res)
        recs.append({"source_table": inv["source_table"], "tier": inv["tier"], "size_gb": inv["size_gb"],
                     "cursor_column": inv["cursor_column"], "recommended_load_mode": mode,
                     "recommended_deletes": deletes, "reasons": "; ".join(reasons)})
        updated.append({**{k: v for k, v in inv.items() if k != "cursor_type"}, "load_mode": mode, "deletes": deletes,
                        "primary_keys": inv["primary_keys"]})

    outdir = Path(outdir)
    rec_path, inv_path = outdir / "load_mode_recommendations.csv", outdir / "tables_with_load_mode.csv"
    with open(rec_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(recs[0].keys()))
        w.writeheader()
        w.writerows(recs)
    with open(inv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(updated[0].keys()))
        w.writeheader()
        w.writerows(updated)

    counts = {}
    for r in recs:
        counts[r["recommended_load_mode"]] = counts.get(r["recommended_load_mode"], 0) + 1
    print(", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    before = {r["source_table"]: (r.get("deletes") or "none") for r in inv_rows}
    for r in recs:
        if r["recommended_load_mode"] != "incremental" or r["recommended_deletes"] != before[r["source_table"]]:
            print(f"  {r['source_table']:<20} {r['recommended_load_mode']:<22} {r['reasons']}")
    print(f"Wrote {rec_path} and {inv_path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("emit", help="print the check SQL to run in your SQL tool")
    e.add_argument("inventory")
    e.add_argument("--owner", required=True)
    e.add_argument("--only", help="comma-separated tables to check (start with a few; one statement over a whole ERP is slow)")
    rc = sub.add_parser("recommend", help="turn exported check results into recommendations")
    rc.add_argument("inventory")
    rc.add_argument("results")
    rn = sub.add_parser("run", help="connect with oracledb, check, and recommend in one step")
    rn.add_argument("inventory")
    rn.add_argument("--owner", required=True)
    rn.add_argument("--only", help="comma-separated tables to check")
    a = ap.parse_args()

    rows = read_inventory(a.inventory)
    if getattr(a, "only", None):
        keep = {t.strip().upper() for t in a.only.split(",")}
        rows = [r for r in rows if r["source_table"] in keep]
        if not rows:
            sys.exit("none of --only tables are in the inventory")
    outdir = Path(a.inventory).parent
    if a.cmd == "emit":
        emit(rows, a.owner.upper())
    elif a.cmd == "recommend":
        recommend(rows, list(csv.DictReader(open(a.results))), outdir)
    else:
        recommend(rows, run(rows, a.owner.upper()), outdir)


if __name__ == "__main__":
    main()
